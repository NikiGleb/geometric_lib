def area(a, h):
    '''
        Принимает a, h - основание и высоту, проведённую к этому основанию
        Возвращает площадь данного треугольника.
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''
        Принимает a, b, c - стороны треугольника.
        Возвращает периметр данного треугольника.
    '''
    return a + b + c
