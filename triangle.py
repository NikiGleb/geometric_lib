def area(a, h):
    '''
        Принимает a, h - длину основания и высоты, проведённой к этому основанию
        Возвращает площадь данного треугольника.
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''
        Принимает a, b, c - длину сторон треугольника.
        Возвращает периметр данного треугольника.
    '''
    return a + b + c
