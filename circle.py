import math


def area(r):
    '''
        Принимает r - радиус окржности.
        Возвращает площадь данной кружности.
    '''
    return math.pi * r * r


def perimeter(r):
    '''
        Принимает r - радиус окржности.
        Возвращает периметр данной кружности.
    '''
    return 2 * math.pi * r

