def area(a, b):
    '''
        Принимает a, b - длину и ширину прямоугольника.
        Возвращает площадь данного прямоугьника.
    '''
    return a * b

def perimeter(a, b):
    '''
        Принимает a, b - длину и ширину прямоугольника.
        Возвращает периметр данного прямоугьника.
    '''
    return 2 * (a + b)
